-- PG-026: append-only Live Pilot Guard results.

create table if not exists public.warashibe_live_pilot_guard_results (
  id bigint generated by default as identity primary key,
  guard_key text not null unique,
  decision_key text not null,
  intent_key text not null,
  guard jsonb not null,
  evaluated_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.warashibe_live_pilot_guard_results enable row level security;

create index if not exists warashibe_live_pilot_guard_decision_idx
  on public.warashibe_live_pilot_guard_results (decision_key, evaluated_at desc);

-- No public/anon policies are created.
-- Passing this guard permits live-adapter validation only.
-- It never authorizes order submission, payment, sale, or live execution.
